// Render deploy/security-headers.inc from site/security-headers.json (single source of truth).
import { readFileSync, writeFileSync } from 'node:fs';
const h = JSON.parse(readFileSync(new URL('../site/security-headers.json', import.meta.url), 'utf8'));
const lines = Object.entries(h).map(([k, v]) => `add_header ${k} "${v}" always;`);
writeFileSync(new URL('../deploy/security-headers.inc', import.meta.url), '# Generated by scripts/render-nginx.mjs from site/security-headers.json. Do not edit.\n' + lines.join('\n') + '\n');
console.log('wrote deploy/security-headers.inc');
